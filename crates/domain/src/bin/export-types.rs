use ts_rs::TS;
use video_domain::*;
fn main() -> std::io::Result<()> {
    let output = std::env::args().nth(1).expect("output path");
    let text = [
        Track::decl(),
        Inspection::decl(),
        DownloadOptions::decl(),
        Job::decl(),
        Settings::decl(),
        RuntimeStatus::decl(),
        Movie::decl(),
    ]
    .into_iter()
    .map(|s| format!("export {s}\n"))
    .collect::<String>();
    std::fs::write(
        output,
        format!("// Generated by video-domain; do not edit.\n{text}"),
    )
}
